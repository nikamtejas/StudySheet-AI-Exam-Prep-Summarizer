import type { SummaryDTO } from '@/contracts';
import { renderBody } from '@/lib/highlight';
import { Visual } from '@/components/visuals';

const SECTION_TITLES: Record<string, string> = {
  'in-one-minute': 'In one minute',
  'core-concepts': 'Core concepts',
  formulas: 'Formulas',
  'exam-questions': 'Exam questions',
  'common-confusions': 'Common confusions',
  connections: 'Connections',
  'page-map': 'Page map',
};

// The full study sheet shows each solved problem's setup (given/goal/
// strategy) but not its step-by-step working — full solutions live in the
// answer appendix variant, numbered to match (array position, 1-indexed),
// the same way a textbook separates exercises from its answer key.
export function FullStudySheet({ summary }: { summary: SummaryDTO }) {
  return (
    <article className="study-sheet">
      <header className="sheet-header">
        <h1>Study sheet</h1>
      </header>

      {summary.sections.map((section, i) => (
        <section key={i} className={`section section-${section.type}`}>
          <h2>{SECTION_TITLES[section.type] ?? section.type}</h2>
          {renderBody(section.body, section.highlights)}
        </section>
      ))}

      {summary.definitions.length > 0 && (
        <section className="section section-definitions">
          <h2>Definitions</h2>
          <dl>
            {summary.definitions.map((def, i) => (
              <div key={i} className="definition-row">
                <dt>
                  {def.term}
                  {def.confidence === 'low' && <span className="low-confidence"> (uncertain)</span>}
                </dt>
                <dd>
                  {def.definition} <span className="page-ref">p.{def.pageRef}</span>
                </dd>
              </div>
            ))}
          </dl>
        </section>
      )}

      {summary.examQuestions.length > 0 && (
        <section className="section section-exam-questions">
          <h2>Exam questions</h2>
          <ol>
            {summary.examQuestions.map((q, i) => (
              <li key={i}>
                {q.q} <span className="page-ref">p.{q.pageRef}</span>
                {q.hint && <div className="hint">Hint: {q.hint}</div>}
              </li>
            ))}
          </ol>
        </section>
      )}

      {summary.problems.length > 0 && (
        <section className="section section-problems">
          <h2>Problems</h2>
          {summary.problems.map((problem, i) => (
            <div key={i} className="problem-card">
              <h3>
                Problem {i + 1}
                {!problem.verified && <span className="unverified"> — {problem.verificationNote}</span>}
              </h3>
              <p className="problem-statement">{problem.problem}</p>
              <p>
                <strong>Given:</strong> {problem.given.join('; ')}
              </p>
              <p>
                <strong>Goal:</strong> {problem.goal}
              </p>
              <p>
                <strong>Strategy:</strong> {problem.strategy}
              </p>
              {problem.visual && <Visual spec={problem.visual} />}
              <p className="memory-hook">{problem.memoryHook}</p>
              <p className="see-appendix">Full worked solution: see answer appendix, problem {i + 1}.</p>
            </div>
          ))}
        </section>
      )}

      <footer className="sheet-footer">
        Generated by StudySheet from your uploaded material — verify against your source before an
        exam.
      </footer>
    </article>
  );
}
